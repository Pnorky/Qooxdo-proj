/**
 * Writes myapp/icons/lucide-sprite.svg (SVG symbols) and myapp.util.LucideRegistry (ids + resource path).
 * Run: npm run lucide:registry
 */
import { mkdirSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");

import Menu from "../node_modules/lucide/dist/esm/icons/menu.js";
import Users from "../node_modules/lucide/dist/esm/icons/users.js";
import LayoutGrid from "../node_modules/lucide/dist/esm/icons/layout-grid.js";
import Printer from "../node_modules/lucide/dist/esm/icons/printer.js";
import Sparkles from "../node_modules/lucide/dist/esm/icons/sparkles.js";
import LogOut from "../node_modules/lucide/dist/esm/icons/log-out.js";
import ChevronLeft from "../node_modules/lucide/dist/esm/icons/chevron-left.js";
import ChevronRight from "../node_modules/lucide/dist/esm/icons/chevron-right.js";
import User from "../node_modules/lucide/dist/esm/icons/user.js";
import Mail from "../node_modules/lucide/dist/esm/icons/mail.js";
import BookText from "../node_modules/lucide/dist/esm/icons/book-text.js";
import Table from "../node_modules/lucide/dist/esm/icons/table.js";
import MessageCircle from "../node_modules/lucide/dist/esm/icons/message-circle.js";
import Moon from "../node_modules/lucide/dist/esm/icons/moon.js";
import X from "../node_modules/lucide/dist/esm/icons/x.js";

const ENTRIES = [
  ["menu", Menu],
  ["users", Users],
  ["layout-grid", LayoutGrid],
  ["printer", Printer],
  ["sparkles", Sparkles],
  ["log-out", LogOut],
  ["chevron-left", ChevronLeft],
  ["chevron-right", ChevronRight],
  ["user", User],
  ["mail", Mail],
  ["book-text", BookText],
  ["table", Table],
  ["message-circle", MessageCircle],
  ["moon", Moon],
  ["x", X]
];

function escapeXml(s) {
  return String(s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function serializeChild(node) {
  const tag = node[0];
  const attrs = node[1] || {};
  const children = node[2];
  let attrStr = "";
  for (const k of Object.keys(attrs)) {
    attrStr += ` ${k}="${escapeXml(attrs[k])}"`;
  }
  if (children && children.length) {
    return `<${tag}${attrStr}>${children.map(serializeChild).join("")}</${tag}>`;
  }
  return `<${tag}${attrStr} />`;
}

function buildSymbol(id, iconNode) {
  const inner = iconNode.map(serializeChild).join("");
  return (
    `<symbol id="${escapeXml(id)}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">` +
    inner +
    `</symbol>`
  );
}

const symbols = ENTRIES.map(([id, node]) => buildSymbol(id, node));
const symbolIds = ENTRIES.map(([id]) => id);

const spriteBody =
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="24" height="24" viewBox="0 0 24 24" aria-hidden="true">\n` +
  symbols.map((s) => "  " + s).join("\n") +
  `\n</svg>\n`;

const iconsDir = join(root, "source/resource/myapp/icons");
mkdirSync(iconsDir, { recursive: true });
const spritePath = join(iconsDir, "lucide-sprite.svg");
writeFileSync(spritePath, spriteBody, "utf8");
console.log("Wrote", spritePath);

const header = `/* ************************************************************************
   Copyright: 2026
   AUTO-GENERATED by scripts/lucide-registry.mjs — do not edit by hand.
   Run: npm run lucide:registry
************************************************************************ */

`;

const body = `qx.Class.define("myapp.util.LucideRegistry", {
  type: "static",

  statics: {
    /** Qooxdoo resource id for the SVG sprite (symbols referenced via &lt;use href="...#id"&gt;). */
    SPRITE_RESOURCE_ID: "myapp/icons/lucide-sprite.svg",

    /** Kebab-case symbol ids present in the sprite. */
    SYMBOL_IDS: ${JSON.stringify(symbolIds, null, 2)}
  }
});
`;

const outPath = join(root, "source/class/myapp/util/LucideRegistry.js");
writeFileSync(outPath, header + body, "utf8");
console.log("Wrote", outPath);
